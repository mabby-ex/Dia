package app.dia

import app.dia.data.db.InsulinKind
import app.dia.data.db.LogType
import app.dia.data.libre.LibreViewCsvParser
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.LocalDateTime
import java.time.ZoneId

class LibreViewCsvParserTest {
    private val utc = ZoneId.of("UTC")

    @Test
    fun parsesUsExport() {
        val csv = """
            Glucose Data,Generated on,11-10-2026 10:00 AM UTC,Generated by,Someone
            Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin Value (units),Notes,Strip Glucose mg/dL,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units)
            FreeStyle LibreLink,ABC,11-09-2026 08:15 PM,0,123,,,,,,,,,,,,,,
            FreeStyle LibreLink,ABC,11-09-2026 08:30 PM,1,,130,,,,,,,,,,,,,
            FreeStyle LibreLink,ABC,11-09-2026 08:31 PM,4,,,,4.5,,,,,,,,,,,
            FreeStyle LibreLink,ABC,11-09-2026 08:32 PM,5,,,,,,45,,,,"Pasta, salad",,,,,
            FreeStyle LibreLink,ABC,11-09-2026 10:00 PM,4,,,,,,,,,14,,,,,,
        """.trimIndent()
        val r = LibreViewCsvParser.parse(csv, utc)
        assertEquals(2, r.readings.size)
        assertEquals(123, r.readings[0].mgdl)
        assertEquals(LocalDateTime.of(2026, 11, 9, 20, 15).atZone(utc).toInstant().toEpochMilli(), r.readings[0].timestamp)
        assertEquals(130, r.readings[1].mgdl)

        val rapid = r.entries.single { it.type == LogType.INSULIN && it.subtype == InsulinKind.RAPID }
        assertEquals(4.5, rapid.amount!!, 0.001)
        val long = r.entries.single { it.type == LogType.INSULIN && it.subtype == InsulinKind.LONG }
        assertEquals(14.0, long.amount!!, 0.001)
        assertEquals(45.0, r.entries.single { it.type == LogType.FOOD }.amount!!, 0.001)
        assertEquals("Pasta, salad", r.entries.single { it.type == LogType.NOTE }.note)
    }

    @Test
    fun parsesEuropeanMmolExportWithSemicolons() {
        val csv = """
            Glukosedaten;Erstellt am;10-11-2026 10:00 UTC
            Gerät;Seriennummer;Device Timestamp;Record Type;Historic Glucose mmol/L;Scan Glucose mmol/L
            FreeStyle LibreLink;ABC;25-10-2026 14:00;0;5,5;
            FreeStyle LibreLink;ABC;25-10-2026 14:15;0;10,0;
        """.trimIndent()
        val r = LibreViewCsvParser.parse(csv, utc)
        assertEquals(2, r.readings.size)
        assertEquals(99, r.readings[0].mgdl)
        assertEquals(180, r.readings[1].mgdl)
        assertEquals(LocalDateTime.of(2026, 10, 25, 14, 0).atZone(utc).toInstant().toEpochMilli(), r.readings[0].timestamp)
    }

    @Test
    fun splitHandlesQuotes() {
        assertEquals(listOf("a", "b, c", "d\"e"), LibreViewCsvParser.splitCsv("a,\"b, c\",\"d\"\"e\"", ','))
    }

    @Test(expected = IllegalArgumentException::class)
    fun rejectsUnrelatedFile() {
        LibreViewCsvParser.parse("hello,world\n1,2")
    }

    @Test
    fun skipsBadRows() {
        val csv = "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL\n" +
            "x,y,11-09-2026 08:15 PM,0,100\nx,y,garbage,0,100\n"
        val r = LibreViewCsvParser.parse(csv, utc)
        assertEquals(1, r.readings.size)
        assertTrue(r.skippedRows >= 1)
    }
}
